"""The Gmail filter recipe, generated from the shipped sender list.

`gmail_queries` packs the sender domains into search strings that fit one Gmail filter,
`gmail_doc` is the whole of `docs/gmail-filters.md`, and `python -m tripbox.mail.recipes` prints
it. A test holds the committed file equal to what this writes, so the document follows the list."""

from __future__ import annotations

from collections.abc import Sequence

from tripbox import lists

# Characters in one filter's search: a margin under what Gmail's form accepts.
GMAIL_FILTER_MAX = 1400
_PREFIX = "from:("
_JOIN = " OR "
_SUFFIX = ")"
_MAILBOX = "trips@example.com"


def gmail_queries(domains: Sequence[str], limit: int = GMAIL_FILTER_MAX) -> list[str]:
    """`from:(a OR b ...)` strings, the domains in list order, each as full as `limit` allows.
    A domain that cannot fit a string on its own is a ValueError."""
    room = limit - len(_PREFIX) - len(_SUFFIX)
    queries: list[str] = []
    current: list[str] = []
    used = 0
    for domain in domains:
        if len(domain) > room:
            raise ValueError(f"a sender domain is longer than one filter can hold ({limit})")
        extra = len(domain) + (len(_JOIN) if current else 0)
        if current and used + extra > room:
            queries.append(_PREFIX + _JOIN.join(current) + _SUFFIX)
            current, used, extra = [], 0, len(domain)
        current.append(domain)
        used += extra
    if current:
        queries.append(_PREFIX + _JOIN.join(current) + _SUFFIX)
    return queries


def family_query(addresses: Sequence[str] = ("pat@example.com", "lee@example.com")) -> str:
    """The search for relatives who forward their own bookings to you."""
    return _PREFIX + _JOIN.join(addresses) + _SUFFIX


def gmail_doc(domains: Sequence[str] | None = None) -> str:
    """The whole of docs/gmail-filters.md."""
    chosen = lists.trusted_sender_domains() if domains is None else domains
    queries = gmail_queries(chosen)
    out = [
        "# Gmail filters for tripbox",
        "",
        "Generated from the shipped sender list: do not edit this file by hand (the filters it",
        "describes are yours to change). The addresses below are",
        f"examples: `{_MAILBOX}` stands for the mailbox tripbox reads, and the other",
        "addresses for yours.",
        "",
        "tripbox reads one mailbox. Your Gmail forwards travel confirmations to it with filters.",
        "",
        "## Add the forwarding address",
        "",
        "1. In Gmail, open Settings, then See all settings, then Forwarding and POP/IMAP.",
        f"2. Choose Add a forwarding address and enter `{_MAILBOX}`.",
        "3. Gmail sends a confirmation message to that mailbox. Open it there and follow its link,",
        "   or copy its code back into Gmail.",
        "4. Leave the forwarding option on Disable forwarding: the filters below forward.",
        "",
        "## Create the filters",
        "",
        "For each filter below: paste the search into Gmail's search box, open Show search options",
        "at the right end of the box, choose Create filter, tick Forward it to, pick",
        f"`{_MAILBOX}`, and choose Create filter.",
        "",
    ]
    for number, query in enumerate(queries, start=1):
        out += [f"{number}. Search for:", "", f"   `{query}`", ""]
    out += [
        "## Senders the list does not hold",
        "",
        "The searches above cover airlines and booking sites only, mostly North American",
        "ones. They name no hotel chain, car rental, railway or home-rental site, and no",
        "low-cost European or Asian airline. Add a filter of your own for the domains your",
        "confirmations come from, in the same form (`from:(hotel.example OR rail.example)`),",
        "and forward it the same way. A filter forward from a domain outside the list is read",
        "like any other; the list only",
        "decides which of your flights skip your look before they go to a flight log.",
        "",
        "## Relatives who forward their own bookings",
        "",
        "If a relative forwards their own confirmations to you, add one more filter with this",
        "search (replace the addresses with theirs), and forward it the same way:",
        "",
        f"`{family_query()}`",
        "",
        "## What tripbox checks",
        "",
        "With `TRIPBOX_MAIL_TRUST=gmail`, tripbox reads a message only when Gmail's own",
        "authentication results show it came from, or was forwarded by a Gmail filter for, an",
        "allowed sender. Everything else is kept unread.",
    ]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    print(gmail_doc(), end="")
